#!/usr/bin/env python3
"""Package-manager manifests generated from a release's .sha256 files.

Each manager only needs where to download the binary and its SHA-256, and both come from the
release itself, so nothing here is edited by hand. The release workflow runs this after the
assets are built and pushes the results to the Homebrew tap, the Scoop bucket and the AUR.

Usage: scripts/pacotes.py <tag> <dist-dir> <out-dir>
  writes <out>/homebrew/Formula/papo.rb, <out>/aur/{PKGBUILD,.SRCINFO}, <out>/scoop/papo.json
"""

import json
import sys
from pathlib import Path

REPO = "https://github.com/Kelvin-Jesus/papo"
DESCRICAO = "Direct P2P line between the Claude Code agents of different people"
TARGETS = {
    "x86_64-unknown-linux-musl": "tar.gz",
    "aarch64-unknown-linux-musl": "tar.gz",
    "x86_64-apple-darwin": "tar.gz",
    "aarch64-apple-darwin": "tar.gz",
    "x86_64-pc-windows-msvc": "zip",
}


def arquivo(tag: str, target: str) -> str:
    return f"papo-{tag}-{target}.{TARGETS[target]}"


def url(tag: str, target: str) -> str:
    return f"{REPO}/releases/download/{tag}/{arquivo(tag, target)}"


def ler_checksums(dist: Path, tag: str) -> dict[str, str]:
    sums = {}
    for target in TARGETS:
        f = dist / f"{arquivo(tag, target)}.sha256"
        if not f.is_file():
            sys.exit(f"pacotes: falta {f.name}; a release não tem todos os alvos")
        sums[target] = f.read_text().split()[0].lower()
    return sums


def formula_homebrew(tag: str, sums: dict[str, str]) -> str:
    def plataforma(target: str) -> str:
        return f'      url "{url(tag, target)}"\n      sha256 "{sums[target]}"'

    return f'''class Papo < Formula
  desc "{DESCRICAO}"
  homepage "https://kelvin-jesus.github.io/papo/"
  version "{tag.removeprefix("v")}"
  license "MIT"

  on_macos do
    on_arm do
{plataforma("aarch64-apple-darwin")}
    end
    on_intel do
{plataforma("x86_64-apple-darwin")}
    end
  end

  on_linux do
    on_arm do
{plataforma("aarch64-unknown-linux-musl")}
    end
    on_intel do
{plataforma("x86_64-unknown-linux-musl")}
    end
  end

  def install
    bin.install "papo"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/papo --version")
  end
end
'''


def pkgbuild_aur(tag: str, sums: dict[str, str]) -> str:
    v = tag.removeprefix("v")
    x64, arm = "x86_64-unknown-linux-musl", "aarch64-unknown-linux-musl"
    return f"""# Generated by scripts/pacotes.py in {REPO}; edit there, not here.
pkgname=papo-bin
pkgver={v}
pkgrel=1
pkgdesc="{DESCRICAO}"
arch=('x86_64' 'aarch64')
url="{REPO}"
license=('MIT')
provides=('papo')
conflicts=('papo')
options=('!debug' '!strip')
source_x86_64=("{url(tag, x64)}")
source_aarch64=("{url(tag, arm)}")
sha256sums_x86_64=('{sums[x64]}')
sha256sums_aarch64=('{sums[arm]}')

package() {{
  cd "papo-v${{pkgver}}-${{CARCH}}-unknown-linux-musl"
  install -Dm755 papo "$pkgdir/usr/bin/papo"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
}}
"""


def srcinfo_aur(tag: str, sums: dict[str, str]) -> str:
    v = tag.removeprefix("v")
    x64, arm = "x86_64-unknown-linux-musl", "aarch64-unknown-linux-musl"
    return f"""pkgbase = papo-bin
\tpkgdesc = {DESCRICAO}
\tpkgver = {v}
\tpkgrel = 1
\turl = {REPO}
\tarch = x86_64
\tarch = aarch64
\tlicense = MIT
\tprovides = papo
\tconflicts = papo
\toptions = !debug
\toptions = !strip
\tsource_x86_64 = {url(tag, x64)}
\tsha256sums_x86_64 = {sums[x64]}
\tsource_aarch64 = {url(tag, arm)}
\tsha256sums_aarch64 = {sums[arm]}

pkgname = papo-bin
"""


def manifesto_scoop(tag: str, sums: dict[str, str]) -> str:
    win = "x86_64-pc-windows-msvc"
    return json.dumps(
        {
            "version": tag.removeprefix("v"),
            "description": DESCRICAO,
            "homepage": "https://kelvin-jesus.github.io/papo/",
            "license": "MIT",
            "architecture": {
                "64bit": {
                    "url": url(tag, win),
                    "hash": sums[win],
                    "extract_dir": f"papo-{tag}-{win}",
                }
            },
            "bin": "papo.exe",
            "checkver": "github",
            "autoupdate": {
                "architecture": {
                    "64bit": {
                        "url": f"{REPO}/releases/download/v$version/papo-v$version-{win}.zip",
                        "hash": {"url": "$url.sha256"},
                        "extract_dir": f"papo-v$version-{win}",
                    }
                }
            },
        },
        indent=2,
        ensure_ascii=False,
    ) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    tag, dist, out = argv[0], Path(argv[1]), Path(argv[2])
    sums = ler_checksums(dist, tag)
    saidas = {
        out / "homebrew/Formula/papo.rb": formula_homebrew(tag, sums),
        out / "aur/PKGBUILD": pkgbuild_aur(tag, sums),
        out / "aur/.SRCINFO": srcinfo_aur(tag, sums),
        out / "scoop/papo.json": manifesto_scoop(tag, sums),
    }
    for caminho, conteudo in saidas.items():
        caminho.parent.mkdir(parents=True, exist_ok=True)
        caminho.write_text(conteudo)
        print(f"pacotes: {caminho}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
